// 이 앱은 사용자가 쓴 글을 화면에 넣을 때 절대 innerHTML 을 쓰지 않습니다.
// 항상 h() 로 요소를 만들고 글자는 "텍스트"로만 넣기 때문에,
// 누군가 <script> 같은 코드를 글에 써도 실행되지 않고 그냥 글자로 보입니다 (XSS 방어).

// ---- 안전장치 ---------------------------------------------------------------
// 브라우저 기본 append()/replaceChildren() 는 null, false 를 "null", "false" 라는 글자로 화면에 찍고,
// 배열은 "a,b" 처럼 글자로 바꿔 버립니다. (예: `isAdmin() && h('a', …)` 가 거짓이면 화면에 "false" 가 보임)
// 이 앱은 시작할 때 한 번, 빈 값은 건너뛰고 배열은 펼쳐서 넣도록 바꿔 둡니다. => 같은 실수가 다시 생겨도 안전합니다.
for (const proto of [Element.prototype, DocumentFragment.prototype]) {
  for (const name of ['append', 'prepend', 'replaceChildren']) {
    const native = proto[name];
    if (!native || native.__safe) continue;
    const safe = function (...nodes) {
      return native.apply(this, nodes.flat(Infinity).filter((n) => n != null && n !== false && n !== true));
    };
    safe.__safe = true;
    proto[name] = safe;
  }
}
for (const name of ['after', 'before']) {
  const native = Element.prototype[name];
  if (!native || native.__safe) continue;
  const safe = function (...nodes) {
    return native.apply(this, nodes.flat(Infinity).filter((n) => n != null && n !== false && n !== true));
  };
  safe.__safe = true;
  Element.prototype[name] = safe;
}

export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  if (attrs) {
    for (const [k, v] of Object.entries(attrs)) {
      if (v == null || v === false) continue;
      if (k === 'class') el.className = v;
      else if (k === 'for') el.htmlFor = v;
      else if (k === 'dataset') Object.assign(el.dataset, v);
      else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
      else if (k in el && k !== 'list' && k !== 'form') el[k] = v;
      else el.setAttribute(k, v === true ? '' : v);
    }
  }
  append(el, children);
  return el;
}

export function append(parent, children) {
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    parent.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return parent;
}

export function clear(el) {
  el.replaceChildren();
  return el;
}

